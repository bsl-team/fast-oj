-- 0021: 提交的版本选项。
--
-- 同一段代码用 c++11 编和用 c++20 编、开 O2 和不开 O2，判出来的不是一回事；出了争议
-- 要能看出当时到底用的哪一条命令行。所以这一列记的是**提交当时的选择**，不是题目属性。
--
-- 格式是判机白名单里的 "轴=值" 逗号串（"std=c++14,O=0"），空串表示"没选，用这台判机的
-- 默认口径"。默认口径本身写在代码里（c++17 + O2，也就是拆成选项之前硬编码的那一套），
-- 所以老数据一个字节都不用改，判定基准也不变。
--
-- 值必须是候选表里的原话，判机才肯把它拼进命令行：这一列被直接写进 argv 的只有查表
-- 得到的那几个参数，用户文本永远进不去。
ALTER TABLE submissions ADD COLUMN options TEXT NOT NULL DEFAULT '';
