-- 0031: 改权限之前要再证一次身份，有效期两分钟。
--
-- 症状是"session cookie 一被拿走，权限就能被随便改"：CSRF 挡的是别人替你点按钮，
-- 挡不住拿到你 cookie 的人；而权限控制台改的是"谁能做什么"，是这条链上最值钱的一扇门。
-- 所以这里加一次密码再确认：动权限之前把密码再输一遍，确认后 2 分钟内这一路的改动不再问。
--
-- 为什么记在 sessions 上而不是 users 上：这次确认属于"这台浏览器的这一个会话"。记在账号上
-- 的话，手机上的确认会给网页上的会话开门，异地两个会话互相背书——那正是要防的形态；而且
-- 会话被偷时，攻击者的那个会话自己背着失败次数，踢掉它不影响本人另一个设备上的工作。
--
-- 默认 0（从没确认过）而不是"建会话时写进去"：登录成功不等于"刚刚证明过密码"——拿着记住的
-- 密码登录、或者 cookie 被种下，都不该自带这 2 分钟。这一列只可能由一次真的密码比对写成非 0。
ALTER TABLE sessions ADD COLUMN step_up_at INTEGER NOT NULL DEFAULT 0;
