-- 0029: 复选框那一下要有服务端记录。
--
-- 0028 之后那一步是"表单带着令牌、时间到了就放行"，实测（curl）暴露了问题：拿到令牌以后
-- 睡够秒数、直接交表单，全程不需要任何浏览器行为——复选框成了纯装饰。这张表补一个
-- verified 列，勾复选框时页面必须真的发一次 POST /verify，服务端只在**等待时间已经走完**
-- 的时候把它盖成 1；注册/登录只接受 verified=1 的令牌，于是"点一下"从观感变成了必经的一站。
--
-- 为什么还留着 ready_at 而不是只靠这一次点击：点击本身能被脚本模仿（一次 HTTP 请求而已），
-- 但它模仿不了"已经过去的时间"。两道叠在一起，脚本要过的就是"等 + 两次绑定同一令牌的请求"，
-- 而不是"等 + 一次提交"。
ALTER TABLE verify_challenges ADD COLUMN verified INTEGER NOT NULL DEFAULT 0;

-- 清掉 0028 那次部署后可能还挂在表里的旧窗口：它们没有点过，verified 默认 0，
-- 留着只会让人以为"页面开了就能直接提交"。
DELETE FROM verify_challenges;
