-- 0030: 每个人自己的配色。
--
-- 站点的观感今天只由 style.css 一处决定：浅色/深色跟着系统走，颜色是写死在 :root 里的。
-- 这一列把"我的 fast-oj 长什么样"交回给每个人——九个颜色变量加一个明暗模式，随他自己的
-- 账号走，跟别人完全无关（别人看同一个站仍然是他们自己的配色）。
--
-- 为什么存成一串 key=value 而不是九个列：这九个东西总是一起读写，九个列要么让每次读多带
-- 九个字段、要么让"没改过"和"改成默认色"分不清（NULL 与 '' 的老问题）。一串文本的代价是
-- 读写各一次解析，而解析的就是九次字符串比较——在页面渲染这条路上，这点开销远小于它省下的
-- 九列 SELECT 列表维护。
--
-- 为什么这一列存的必须是"校验过的值"而不是任意 CSS：这个字段会被拼进 <html style="…">，
-- 那是 CSS 上下文而不是 HTML 上下文，一个 `}` 或 `;` 就能改写出新规则。所以写入侧只认固定
-- 键名 + `#rrggbb`（见 internal/store/theme.go 的 ParseTheme），渲染侧再挡一遍：库里被手工
-- 塞进什么脏东西，也只会掉出来一个不认的键，不会拼出可执行的样式。
--
-- 默认空串 = 这个人什么都没调，跟着站点默认与系统深浅色走；这也让绝大多数请求走的是
-- "两个字段都是空"那条最便宜的渲染路径。
ALTER TABLE users ADD COLUMN theme TEXT NOT NULL DEFAULT '';
