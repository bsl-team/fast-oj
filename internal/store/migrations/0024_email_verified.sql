-- 0024: 邮箱验证的状态位（M25f）。
--
-- DEFAULT 1（视为已验证）是刻意的，不是偷懒：SQLite 给新加的列回填的就是这个默认值，
-- 所以升级前注册的所有老账号都读成"验证过了"。要是默认 0，管理员一跑迁移，全站老用户
-- 立刻被未验证闸门拦在提交与比赛外面，而他们从来没收过验证邮件——一次功能升级就变成了
-- 一次全站锁死，而且没有任何邮件可点。
--
-- 只有这次改动之后新建的注册账号才可能被写成 0，且只在站点开关
-- site.require_email_verification 打开时（见 0025 与 internal/store/email.go）。
-- 管理员批量建号与判机/令牌用的账号走的是另一条插入路径，拿到的同样是 1。
ALTER TABLE users ADD COLUMN email_verified INTEGER NOT NULL DEFAULT 1;
